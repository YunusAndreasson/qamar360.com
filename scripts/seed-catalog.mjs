// Generates supabase/seeds/catalog.sql from the app's hardcoded catalog constants.
//
// The TypeScript constants (src/constants/sunnah-habits.ts, src/lib/dates.ts) stay the
// source of truth during the migration to a shared DB; this script emits an idempotent
// SQL seed so the Supabase catalog tables match them verbatim — diacritics and
// apostrophes included — with no hand-transcription.
//
//   npm run seed:catalog                                   # writes the .sql (no DB)
//   supabase db query --linked -f supabase/seeds/catalog.sql   # applies it
//
// Node 25 strips the TS types natively; the only thing it can't do out of the box is
// resolve the app's `@/*` tsconfig alias, so we register a tiny in-process resolve hook
// that maps `@/x` -> <repo>/src/x.ts before importing the constants.

import { registerHooks } from 'node:module';
import { pathToFileURL } from 'node:url';
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const srcRoot = pathToFileURL(path.resolve(import.meta.dirname, '..', 'src') + path.sep).href;
registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier.startsWith('@/')) {
      return nextResolve(srcRoot + specifier.slice(2) + '.ts', context);
    }
    return nextResolve(specifier, context);
  },
});

const { SUNNAH_CATEGORIES, SUNNAH_PRESETS, SUNNAH_ROUTINES } = await import('@/constants/sunnah-habits');
const { HIJRI_MONTHS } = await import('@/lib/dates');

// ── SQL literal helpers ────────────────────────────────────────────────────
const q = (s) => `'${String(s).replace(/'/g, "''")}'`; // text (single-quote-escaped)
const qn = (s) => (s == null ? 'null' : q(s)); //           nullable text
const num = (n) => (n == null ? 'null' : String(n)); //     nullable int
const bool = (b) => (b ? 'true' : 'false');
const intArray = (arr) => `'{${arr.join(',')}}'::integer[]`;
const jsonb = (obj) => (obj == null ? 'null' : `${q(JSON.stringify(obj))}::jsonb`);

const out = [];
out.push('-- GENERATED by scripts/seed-catalog.mjs — do not edit by hand.');
out.push('-- Idempotent seed of the shared Sunnah catalog (re-runnable).');
out.push('begin;');
out.push('');

out.push('insert into public.categories (id, title, sort_order) values');
out.push(SUNNAH_CATEGORIES.map((c, i) => `  (${q(c.id)}, ${q(c.title)}, ${i})`).join(',\n'));
out.push('on conflict (id) do update set title = excluded.title, sort_order = excluded.sort_order;');
out.push('');

out.push(
  'insert into public.presets (id, category_id, name, detail, evidence, default_schedule, hijri_schedule, target_count, target_unit, essential, sort_order) values',
);
out.push(
  SUNNAH_PRESETS.map(
    (p, i) =>
      `  (${q(p.id)}, ${q(p.categoryId)}, ${q(p.name)}, ${q(p.detail)}, ${q(p.evidence)}, ` +
      `${intArray(p.defaultSchedule)}, ${jsonb(p.hijriSchedule ?? null)}, ${num(p.targetCount ?? null)}, ` +
      `${qn(p.targetUnit ?? null)}, ${bool(p.essential ?? false)}, ${i})`,
  ).join(',\n'),
);
out.push(
  'on conflict (id) do update set category_id = excluded.category_id, name = excluded.name, ' +
    'detail = excluded.detail, evidence = excluded.evidence, default_schedule = excluded.default_schedule, ' +
    'hijri_schedule = excluded.hijri_schedule, target_count = excluded.target_count, ' +
    'target_unit = excluded.target_unit, essential = excluded.essential, sort_order = excluded.sort_order;',
);
out.push('');

out.push('insert into public.routines (id, name, detail, sort_order) values');
out.push(SUNNAH_ROUTINES.map((r, i) => `  (${q(r.id)}, ${q(r.name)}, ${q(r.detail)}, ${i})`).join(',\n'));
out.push('on conflict (id) do update set name = excluded.name, detail = excluded.detail, sort_order = excluded.sort_order;');
out.push('');

// Membership is fully rebuilt so a removed member never lingers.
const members = SUNNAH_ROUTINES.flatMap((r) =>
  r.presetIds.map((pid, pos) => `  (${q(r.id)}, ${q(pid)}, ${pos})`),
);
out.push('delete from public.routine_presets;');
out.push('insert into public.routine_presets (routine_id, preset_id, position) values');
out.push(members.join(',\n') + ';');
out.push('');

out.push('insert into public.hijri_months (month, name) values');
out.push(HIJRI_MONTHS.map((n, i) => `  (${i + 1}, ${q(n)})`).join(',\n'));
out.push('on conflict (month) do update set name = excluded.name;');
out.push('');

out.push('commit;');
out.push('');

const outPath = path.resolve(import.meta.dirname, '..', 'supabase', 'seeds', 'catalog.sql');
mkdirSync(path.dirname(outPath), { recursive: true });
writeFileSync(outPath, out.join('\n'), 'utf8');
console.log(
  `Wrote ${path.relative(process.cwd(), outPath)}: ` +
    `${SUNNAH_CATEGORIES.length} categories, ${SUNNAH_PRESETS.length} presets, ` +
    `${SUNNAH_ROUTINES.length} routines, ${members.length} routine members, ${HIJRI_MONTHS.length} months.`,
);
