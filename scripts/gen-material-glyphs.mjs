// Generate src/constants/material-glyphs.ts — the Material Symbols codepoints for every Android
// glyph the icon registry names (`md:` in src/constants/icons.ts).
//
// Android draws the app's icons from Material Symbols, the family the SDK 58 tab bar already uses
// (expo-symbols), through an icon font rather than `SymbolView`: the font is preloaded at the root,
// so a glyph paints on its first frame. An icon font needs a name → codepoint map, and the full
// map (4,000+ names) has no business in the bundle; this writes only the ones the registry uses,
// read from expo-symbols' own map so the codepoints match the font it ships. Unknown names fail
// loudly here rather than drawing a blank glyph on a device.
//
//   npm run gen:glyphs        (after adding or changing an `md:` name in icons.ts)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const registry = readFileSync(join(root, 'src/constants/icons.ts'), 'utf8');
const symbols = JSON.parse(readFileSync(join(root, 'node_modules/expo-symbols/build/android/symbols.json'), 'utf8'));

const names = [...new Set([...registry.matchAll(/\bmd: '([a-z0-9_]+)'/g)].map((m) => m[1]))].sort();
const unknown = names.filter((name) => !(name in symbols));
if (unknown.length > 0) {
  console.error(`Not in Material Symbols: ${unknown.join(', ')}`);
  process.exit(1);
}

const body = names.map((name) => `  ${name}: 0x${symbols[name].toString(16)},`).join('\n');
writeFileSync(
  join(root, 'src/constants/material-glyphs.ts'),
  `// Generated by scripts/gen-material-glyphs.mjs from the icon registry (\`md:\` in icons.ts) and
// expo-symbols' Material Symbols map. Do not edit by hand: run \`npm run gen:glyphs\`.

/** Material Symbols codepoints for the registry's Android glyphs. */
export const MaterialGlyphs = {
${body}
} as const;

export type MaterialGlyphName = keyof typeof MaterialGlyphs;
`,
);
console.log(`Wrote ${names.length} Material Symbols glyphs to src/constants/material-glyphs.ts`);
