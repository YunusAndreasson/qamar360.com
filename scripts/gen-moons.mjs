#!/usr/bin/env node
/**
 * Render the moon images a lunar update attaches on iOS.
 *
 * One PNG per milestone day × month length — the same four phases the notification can name,
 * drawn with the same geometry `src/lib/moon.ts` uses and the same two colours
 * `src/components/moon-phase.tsx` paints with. So the moon on the lock screen, the moon in the
 * Settings sheet and the moon on the Progress hero are one object seen three times.
 *
 * The geometry and the palette are duplicated here rather than imported, because this is a
 * plain Node script and the originals are TypeScript. `src/lib/__tests__/moon.test.ts` pins the
 * resulting paths and `src/constants/__tests__/theme-contract.test.ts` pins the colours, both
 * against the live modules — so drift fails `npm run verify` rather than shipping a wrong moon.
 * (Same arrangement as the `expo-notifications` tint already hardcoded in app.json.)
 *
 * Requires rsvg-convert (librsvg). Run from the repo root:
 *   npm run gen:moons
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'assets/images/moons');
const CONSTANTS = join(ROOT, 'src/constants/moon-assets.ts');
const TMP_DIR = join(ROOT, 'node_modules/.cache/gen-moons');

/** Mirrors `MILESTONE_DAYS` in src/lib/lunar-phase.ts. */
const MILESTONE_DAYS = [1, 8, 15, 22];
/** The two lengths an Umm al-Qura month can have. */
const MONTH_LENGTHS = [29, 30];

/** Mirrors `Colors.dark.complete` — the warm moonglow the app paints lit moons with. */
const LIT = '#F4EACB';
/** Mirrors `Colors.dark.backgroundElement` — the shadowed limb. */
const SHADOW = '#12161D';
/** Mirrors `FAINT` in src/components/moon-phase.tsx. */
const FAINT = 0.14;

const SIZE = 512;
const MARGIN = 24; // keeps the disc clear of a rounded thumbnail crop
const R = (SIZE - MARGIN * 2) / 2;
const C = SIZE / 2;

/** Mirrors `moonIllumination` in src/lib/moon.ts. */
function moonIllumination(dayOfMonth, monthLength) {
  const p = monthLength > 0 ? (dayOfMonth - 1) / monthLength : 0;
  return { illumination: (1 - Math.cos(2 * Math.PI * p)) / 2, waxing: p <= 0.5 };
}

/** Mirrors `moonPhasePath` in src/lib/moon.ts. */
function moonPhasePath(cx, cy, r, illumination, waxing) {
  const top = cy - r;
  const bottom = cy + r;
  const rx = r * Math.abs(1 - 2 * illumination);
  const outerSweep = waxing ? 1 : 0;
  const termSweep = waxing ? (illumination <= 0.5 ? 0 : 1) : illumination <= 0.5 ? 1 : 0;
  return `M ${cx} ${top} A ${r} ${r} 0 0 ${outerSweep} ${cx} ${bottom} A ${rx} ${r} 0 0 ${termSweep} ${cx} ${top} Z`;
}

/** Mirrors `milestoneAssetKey` in src/lib/lunar-phase.ts. */
const assetKey = (day, length) => `d${String(day).padStart(2, '0')}-l${length}`;

function svgFor(day, length) {
  const { illumination, waxing } = moonIllumination(day, length);
  // Same three layers as <MoonPhase>: opaque shadowed disc, a faint wash of the moon's own
  // light across all of it, then the lit region on top.
  const lit =
    illumination > 0.005
      ? `\n  <path d="${moonPhasePath(C, C, R, illumination, waxing)}" fill="${LIT}"/>`
      : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
  <circle cx="${C}" cy="${C}" r="${R}" fill="${SHADOW}"/>
  <circle cx="${C}" cy="${C}" r="${R}" fill="${LIT}" fill-opacity="${FAINT}"/>${lit}
</svg>
`;
}

rmSync(TMP_DIR, { recursive: true, force: true });
mkdirSync(TMP_DIR, { recursive: true });
mkdirSync(OUT_DIR, { recursive: true });

const keys = [];
for (const length of MONTH_LENGTHS) {
  for (const day of MILESTONE_DAYS) {
    const key = assetKey(day, length);
    keys.push(key);
    const svgPath = join(TMP_DIR, `${key}.svg`);
    writeFileSync(svgPath, svgFor(day, length));
    execFileSync('rsvg-convert', ['-w', String(SIZE), '-h', String(SIZE), svgPath, '-o', join(OUT_DIR, `${key}.png`)]);
  }
}
rmSync(TMP_DIR, { recursive: true, force: true });

const entries = keys.map((key) => `  '${key}': require('../../assets/images/moons/${key}.png'),`).join('\n');
writeFileSync(
  CONSTANTS,
  `/**
 * The moon images a lunar update attaches on iOS, keyed by {@link milestoneAssetKey}.
 *
 * GENERATED by \`npm run gen:moons\` — do not edit by hand. The renderer duplicates the geometry
 * in \`src/lib/moon.ts\`; \`moon.test.ts\` pins the two together.
 */

export const MOON_ASSETS: Record<string, number> = {
${entries}
};
`,
);

console.log(`Rendered ${keys.length} moons into assets/images/moons and wrote src/constants/moon-assets.ts`);
