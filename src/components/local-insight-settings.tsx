import { useEffect, useState, useSyncExternalStore } from 'react';

import { SettingsRow } from '@/components/settings-row';
import { SettingsSection } from '@/components/settings-section';
import { useAuth } from '@/hooks/use-auth';
import { useLocalInsightArchive } from '@/hooks/use-local-insights';
import { confirmDestructive } from '@/lib/alerts';
import {
  cancelInsightDownload,
  downloadInsightModel,
  insightModelState,
  refreshInsightModel,
  removeInsightModel,
  subscribeInsightModel,
} from '@/lib/local-insight-model';
import { clearLocalInsights, setLocalJournalUse } from '@/lib/local-insight-store';

export function LocalInsightSettings() {
  const { user } = useAuth();
  const archive = useLocalInsightArchive();
  const model = useSyncExternalStore(subscribeInsightModel, insightModelState, insightModelState);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    void refreshInsightModel();
  }, []);
  const run = (action: () => void | Promise<void>) => {
    void Promise.resolve()
      .then(action)
      .catch(() => setError('Could not update on-device reflections. Please try again.'));
  };
  return (
    <SettingsSection
      title="On-device reflections"
      footer={
        error ??
        model.error ??
        'Reflections are generated by a model on this device and are never uploaded. They are removed if the app’s data is cleared, and the model may need downloading again if the system frees up storage.'
      }
    >
      <SettingsRow
        icon="sparkle"
        label="Model"
        sublabel={
          model.busy
            ? `Downloading · ${Math.round(model.progress * 100)}%`
            : model.ready
              ? 'Gemma 4 E2B · on this device'
              : 'Gemma 4 E2B · 2.7 GB download'
        }
        onPress={model.busy ? cancelInsightDownload : model.ready ? undefined : () => void downloadInsightModel()}
        value={model.busy ? 'Cancel' : model.ready ? 'Ready' : 'Download'}
      />
      {model.ready ? (
        <SettingsRow
          icon="deleteOutline"
          label="Remove the model"
          sublabel="Frees 2.7 GB. Generated reflections stay."
          onPress={() => run(removeInsightModel)}
        />
      ) : null}
      <SettingsRow
        icon="privacy"
        label="Include journal notes"
        sublabel="Read only on this device. Turning this off deletes versions that used them."
        switchValue={archive?.notesEnabled ?? false}
        onSwitchChange={(enabled) => {
          if (user) run(() => setLocalJournalUse(user.id, enabled));
        }}
      />
      <SettingsRow
        icon="deleteOutline"
        label="Delete generated reflections"
        sublabel="Removes every version and the quarter records kept for generating them"
        destructive
        onPress={() =>
          confirmDestructive({
            title: 'Delete generated reflections?',
            message:
              'Every generated reflection on this device, and the quarter records kept for generating them, will be removed. Your journal and habits stay.',
            onConfirm: () => {
              if (user) run(() => clearLocalInsights(user.id));
            },
          })
        }
      />
    </SettingsSection>
  );
}
